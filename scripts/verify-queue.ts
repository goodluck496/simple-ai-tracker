const app = createContainer({ config: { appRoot: root, dbPath: path.join(root, 'data', 'tracker.db'),
  webDistDir: path.resolve(import.meta.dirname, '../dist/web/browser') }, logger: new SilentLogger() });
const server = createApiServer(app);
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
try {
  const settings: AutomationSettings = { ...structuredClone(DEFAULT_AUTOMATION_SETTINGS), repositoryPath: '/fixture',
    connections: [{ id: 'native', label: 'Codex', kind: 'native', supportsImages: false }],
    agents: STANDARD_TEAM_ROLES.map((role) => ({ id: role, role, runner: 'codex', model: 'fixture-model', connectionId: 'native', instructions: '' })),
    pipeline: [...STANDARD_TEAM_ROLES], checks: [{ command: 'npm', args: ['test'] }] };
  const service = app.automationService; service.configure(settings);
  const task = app.taskService.createTask({ title: 'Queue acceptance task' });
  const initial = service.enqueue(task.id);
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(15000);
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error' && !message.text().includes('409')) errors.push(message.text()); });
  await page.goto(`http://127.0.0.1:${(server.address() as AddressInfo).port}`);
  await page.getByRole('button', { name: 'Очередь', exact: true }).click().catch(async (error) => {
    console.error(JSON.stringify({ errors, buttons: await page.locator('button').allTextContents() })); throw error;
  });
  const queue = page.getByRole('dialog', { name: 'Очередь агентов' });
  await queue.getByRole('button', { name: `Запуск ${task.id} ${initial.id}`, exact: true }).click();
  const detail = queue.getByRole('article', { name: 'Детали запуска' });
  await detail.getByText('Нет подключённого worker.', { exact: false }).waitFor();
  const cardDequeue = queue.getByRole('button', { name: 'Убрать из очереди', exact: true }).first();
  assert.equal(await cardDequeue.isVisible(), true);
  let release!: () => void; let entered!: () => void; let requests = 0;
  const gate = new Promise<void>((resolve) => { release = resolve; });
  const began = new Promise<void>((resolve) => { entered = resolve; });
  const initialUrl = `**/api/automation/runs/${initial.id}/dequeue`;
  await page.route(initialUrl, async (route) => { requests++; entered(); await gate; await route.continue(); });
  await cardDequeue.click();
  await began;
  assert.equal(await detail.getByRole('button', { name: 'Убрать из очереди', exact: true }).isDisabled(), true);
  await cardDequeue.dispatchEvent('click');
  assert.equal(requests, 1);
  release();
  await detail.getByText(/Остановлен · карточка:/).waitFor();
  await page.unroute(initialUrl);
  await queue.getByRole('status').filter({ hasText: 'Убрано из очереди.' }).waitFor();
  assert.ok(service.detail(initial.id).events.some((event) => event.text.includes('Убрано из очереди')));
  assert.equal(app.taskService.getTaskCard(task.id).title, 'Queue acceptance task');
  assert.equal(service.claim('must-not-claim-cancelled'), null);
  const requeued = service.enqueue(task.id);
  assert.notEqual(requeued.id, initial.id);
  await queue.getByRole('button', { name: `Запуск ${task.id} ${requeued.id}`, exact: true }).click();
  await detail.getByRole('button', { name: 'Убрать из очереди', exact: true }).click();
  await detail.getByText(/Остановлен · карточка:/).waitFor();
  const third = service.enqueue(task.id);
  await queue.getByRole('button', { name: `Запуск ${task.id} ${third.id}`, exact: true }).click();
  let run: ReturnType<typeof service.claim>;
  const raceUrl = `**/api/automation/runs/${third.id}/dequeue`;
  await page.route(raceUrl, async (route) => { run = service.claim('fixture'); await route.continue(); });
  await detail.getByRole('button', { name: 'Убрать из очереди', exact: true }).click();
  await queue.getByRole('alert').filter({ hasText: 'покинул очередь' }).waitFor();
  assert.ok(run!); assert.equal(service.detail(third.id).run.status, 'running');
  await detail.getByRole('button', { name: 'Остановить', exact: true }).waitFor();
  await page.unroute(raceUrl);
  run = run!;
  const analystAttempt = service.beginStage(run.id, run.leaseToken!);
  const usage = { inputTokens: 1200, outputTokens: 300, cachedInputTokens: 900, reasoningTokens: 100,
    source: UsageSource.Codex, reportedRequests: 1, missingRequests: 0 };
  service.usage(run.id, run.leaseToken!, analystAttempt, usage, false);
  service.progress(run.id, run.leaseToken!, 'Изучаю требования', RunPhase.Agent);
  await detail.getByText('Выполняется · карточка: Планирование', { exact: true }).waitFor();
  const meter = detail.getByRole('region', { name: 'Токенометр', exact: true });
  await meter.getByText(/Токены:.*частичные данные/).waitFor();
  service.usage(run.id, run.leaseToken!, analystAttempt, usage, true);
  await meter.getByText('Токены: 1 500', { exact: true }).waitFor();
  const planRun = service.completeStage(run.id, run.leaseToken!, { verdict: 'pass', summary: 'Plan ready', plan: '# Plan\nImplement and test.' }, `sat/${run.id}`, 'a'.repeat(40));
  service.beginStage(run.id, run.leaseToken!);
  service.progress(run.id, run.leaseToken!, 'Изменяю код', RunPhase.Agent);
  await detail.getByText('Выполняется · карточка: В работе', { exact: true }).waitFor();
  assert.equal(planRun.stage, 1);
  service.fail(run.id, run.leaseToken!, 'Fixture MCP connection failed');
  await detail.getByText('Ошибка · карточка: В работе', { exact: true }).waitFor();
  await detail.getByRole('button', { name: 'Изменить бюджет запуска', exact: true }).click();
  await detail.getByRole('spinbutton', { name: 'Лимит вызовов', exact: true }).fill('9');
  await detail.getByRole('spinbutton', { name: 'Лимит входных токенов', exact: true }).fill('600000');
  await detail.getByRole('button', { name: 'Сохранить лимиты', exact: true }).click();
  await detail.getByRole('button', { name: 'Сохранить лимиты', exact: true }).waitFor({ state: 'hidden' });
  assert.equal(service.detail(run.id).run.settings.maxAgentCalls, 9);
  assert.equal(service.detail(run.id).run.usageAttempts![0].usage!.inputTokens, 1200, 'Budget editing retains spent usage');
  await detail.getByRole('button', { name: 'Продолжить с места остановки', exact: true }).click();
  await detail.getByText('В очереди · карточка: В работе', { exact: true }).waitFor();
  assert.equal(service.detail(run.id).run.settings.agents[0].model, 'fixture-model');
  await meter.getByText('Нет данных', { exact: true }).waitFor();
  const resumed = service.claim('fixture')!;
  assert.equal(resumed.lastMessage, '', 'A new attempt must not display progress from the previous attempt');
  service.fail(resumed.id, resumed.leaseToken!, 'Fixture repeated failure');
  settings.agents[0].model = 'new-model'; service.configure(settings);
  await detail.getByText('Ошибка · карточка: В работе', { exact: true }).waitFor();
  await detail.getByRole('button', { name: 'Начать заново', exact: true }).click();
  await detail.getByText(/повтор запуска/).waitFor();
  const restarted = service.list(task.id).find((entry) => entry.restartedFromId === run.id)!;
  assert.ok(restarted); assert.equal(restarted.settings.agents[0].model, 'new-model'); assert.equal(restarted.stage, 0);
  assert.equal(service.detail(run.id).run.settings.agents[0].model, 'fixture-model');
  await detail.getByRole('button', { name: 'Убрать из очереди', exact: true }).click();
  await detail.getByText('Остановлен · карточка: В работе', { exact: true }).waitFor();
  await detail.getByRole('button', { name: 'Открыть задачу', exact: true }).click();
  await queue.waitFor({ state: 'hidden' });
  const taskDialog = page.getByRole('dialog', { name: 'Карточка задачи', exact: true });
  await taskDialog.waitFor();
  await page.keyboard.press('Escape');
  await taskDialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Очередь', exact: true }).click();
  await queue.getByRole('button', { name: `Запуск ${task.id} ${restarted.id}`, exact: true }).click();
  for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }, { width: 1440, height: 1000 }]) {
    await page.setViewportSize(viewport); assert.ok(await queue.evaluate((element) => element.scrollWidth <= element.clientWidth + 2));
  }
  const waitingTask = app.taskService.createTask({ title: 'Waiting for requirement clarification' });
  service.enqueue(waitingTask.id);
  const waitingRun = service.claim('fixture')!;
  service.beginStage(waitingRun.id, waitingRun.leaseToken!);
  service.completeStage(waitingRun.id, waitingRun.leaseToken!, { verdict: 'questions', summary: 'Need requirement clarification', questions: ['Which behavior?'] }, `sat/${waitingRun.id}`, 'a'.repeat(40));
  await queue.getByRole('button', { name: `Запуск ${waitingTask.id} ${waitingRun.id}`, exact: true }).click();
  await detail.getByRole('button', { name: 'Открыть задачу и ответить на вопросы', exact: true }).waitFor();
  assert.equal(await detail.getByRole('button', { name: 'Продолжить с места остановки', exact: true }).count(), 0);
  app.taskService.answerQuestions({ id: waitingTask.id, answers: [{ answer: 'Use the fixture behavior.' }], actor: 'user' });
  await detail.getByRole('button', { name: 'Начать заново', exact: true }).click();
  const replacement = service.list(waitingTask.id).find((entry) => entry.restartedFromId === waitingRun.id)!;
  assert.ok(replacement); assert.equal(service.detail(waitingRun.id).run.status, 'cancelled');
  await detail.getByText(/повтор запуска/).waitFor();
  await queue.getByRole('button', { name: `Запуск ${task.id} ${run.id}`, exact: true }).click();
  await detail.getByText('Fixture repeated failure', { exact: true }).first().waitFor();
  for (const viewport of [{ width: 390, height: 844 }, { width: 844, height: 390 }, { width: 1440, height: 1000 }]) {
    await page.setViewportSize(viewport);
    assert.ok(await queue.evaluate((element) => element.scrollWidth <= element.clientWidth + 2), 'Token table must scroll within the dialog');
  }
  assert.deepEqual(errors, []);
  const hiddenCard = queue.getByRole('button', { name: `Запуск ${task.id} ${run.id}`, exact: true });
  await detail.getByRole('button', { name: 'Скрыть из списка', exact: true }).click();
  await hiddenCard.waitFor({ state: 'hidden' });
  assert.equal(service.archive().some(entry => entry.id === run.id), true);
  await page.reload();
  await page.getByRole('button', { name: 'Очередь', exact: true }).click();
  assert.equal(await hiddenCard.count(), 0);
  await queue.getByRole('button', { name: 'Архив запусков', exact: true }).click();
  const archive = queue.getByRole('region', { name: 'Архив запусков', exact: true });
  await archive.getByText(new RegExp(run.id)).waitFor();
  await archive.getByRole('button', { name: 'Вернуть в очередь', exact: true }).click();
  await hiddenCard.waitFor();
  assert.equal(service.archive().some(entry => entry.id === run.id), false);
  await hiddenCard.click();
  await detail.getByText('Fixture repeated failure', { exact: true }).first().waitFor();
  for (const queued of service.list().filter(r => r.status === 'queued')) service.dequeue(queued.id);
  const budgetTask = app.taskService.createTask({ title: 'Budget approval UI fixture' });
  const budgetRun = service.enqueue(budgetTask.id, { ...settings, maxAgentCalls: 6 });
  const budgetLease = service.claim('budget-ui')!;
  service.beginStage(budgetRun.id, budgetLease.leaseToken!);
  const waitingBudget = service.completeStage(budgetRun.id, budgetLease.leaseToken!, { verdict: 'pass', summary: 'Analysis completed', plan: '1. Implement two independent deliveries.', decomposition: [
    { key: 'A', title: 'First', description: 'First change.', plan: '1. Implement first.', dependsOn: [] },
    { key: 'B', title: 'Second', description: 'Second change.', plan: '1. Implement second.', dependsOn: [] },
  ] }, `sat/${budgetRun.id}`, 'a'.repeat(40));
  assert.equal(waitingBudget.status, 'running'); assert.equal(waitingBudget.feature?.callBudget?.planned, 7);
  assert.equal(waitingBudget.settings.maxAgentCalls, 10, 'Manual merge does not reserve conflict resolver calls');
  service.fail(budgetRun.id, budgetLease.leaseToken!, 'Pause automatic call budget fixture');
  await page.reload(); await page.getByRole('button', { name: 'Очередь', exact: true }).click();
  await queue.getByRole('button', { name: `Запуск ${budgetTask.id} ${budgetRun.id}`, exact: true }).click();
  await detail.getByLabel('Бюджет вызовов по плану', { exact: true }).waitFor();
  await detail.getByRole('button', { name: 'Продолжить с места остановки', exact: true }).waitFor();
  await detail.getByRole('button', { name: 'Изменить бюджет запуска', exact: true }).click();
  assert.equal(await detail.getByRole('spinbutton', { name: 'Лимит вызовов', exact: true }).inputValue(), '10');
  assert.equal(await detail.getByRole('spinbutton', { name: 'Лимит вызовов', exact: true }).isDisabled(), true);
  await detail.getByRole('spinbutton', { name: 'Лимит входных токенов', exact: true }).fill('600000');
  await detail.getByRole('button', { name: 'Сохранить лимиты', exact: true }).click();
  await detail.getByRole('button', { name: 'Продолжить с места остановки', exact: true }).waitFor();
  assert.equal(service.detail(budgetRun.id).run.settings.maxAgentCalls, 10);
  const featureTask = app.taskService.createTask({ title: 'Feature decomposition UI fixture' });
  const featureRun = service.enqueue(featureTask.id, { ...settings, maxAgentCalls: 12 });
  const featureLease = service.claim('feature-ui')!;
  assert.equal(featureLease.id, featureRun.id);
  service.beginStage(featureRun.id, featureLease.leaseToken!);
  const planned = service.completeStage(featureRun.id, featureLease.leaseToken!, { verdict: 'pass', summary: 'Two planned children', plan: '1. Deliver two changes and test together.', decomposition: [
    { key: 'A', title: 'First delivery', description: 'First isolated change.', plan: '1. Implement first change.', dependsOn: [] },
    { key: 'B', title: 'Second delivery', description: 'Second isolated change.', plan: '1. Implement second change.', dependsOn: ['A'] },
  ] }, `sat/${featureRun.id}`, 'a'.repeat(40));
  service.beginStage(featureRun.id, featureLease.leaseToken!);
  service.completeStage(featureRun.id, featureLease.leaseToken!, { verdict: 'pass', summary: 'Child developed', commitMessage: `[#${planned.feature!.children[0].taskId}] - Добавлено изменение для проверки дочерней задачи` }, `sat/${featureRun.id}`, 'c'.repeat(40));
  service.beginStage(featureRun.id, featureLease.leaseToken!);
  service.completeStage(featureRun.id, featureLease.leaseToken!, { verdict: 'pass', summary: 'Child reviewed and delivered', delivery: { childKey: 'A', sourceSha: 'c'.repeat(40), mergedSha: 'd'.repeat(40) } }, `sat/${featureRun.id}`, 'd'.repeat(40));
  service.fail(featureRun.id, featureLease.leaseToken!, 'Feature UI paused');
  await page.reload(); await page.getByRole('button', { name: 'Очередь', exact: true }).click();
  await queue.getByRole('button', { name: `Запуск ${featureTask.id} ${featureRun.id}`, exact: true }).click();
  const deliveries = detail.getByLabel('Подзадачи фичи', { exact: true });
  await deliveries.getByText('Включена в фичу', { exact: false }).waitFor();
  await deliveries.getByRole('button', { name: `${planned.feature!.children[1].taskId} · Second delivery`, exact: true }).waitFor();
  assert.equal(await deliveries.getByRole('button').count(), 2);
  assert.deepEqual(errors, []);
  const artifacts = path.resolve(import.meta.dirname, '../dist/acceptance'); mkdirSync(artifacts, { recursive: true });
  await meter.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(artifacts, 'automation-queue.png'), fullPage: true });
  console.log('PASS: queue live token usage/unknown attempts/cache, phases/task statuses, failure/resume/restart history, cancel, task link, reopen, responsive table and no browser errors.');
} finally {
  await browser?.close(); server.closeAllConnections(); await new Promise<void>((resolve) => server.close(() => resolve()));
  app.close(); rmSync(root, { recursive: true, force: true });
}
